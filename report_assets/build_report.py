def blank(b, n=1, size=14):
    for _ in range(n):
        p = b.doc.add_paragraph()
        p.paragraph_format.first_line_indent = Cm(0)
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(0)
        _set_run_font(p.add_run(""), size=size)


def cpar(b, text, bold=False, size=14, spacing=1.0, before=0, after=0):
    p = b.doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pf.first_line_indent = Cm(0)
    pf.line_spacing = spacing
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    _set_run_font(p.add_run(text), size=size, bold=bold, color="000000")
    b._need(LINE_PT * spacing)
    return p


def par(b, text, spacing=1.0, first=True, bold=False, after=0, size=14,
        align=WD_ALIGN_PARAGRAPH.JUSTIFY, before=0):
    p = b.doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.first_line_indent = Cm(1.25) if first else Cm(0)
    pf.line_spacing = spacing
    pf.space_before = Pt(before)
    pf.space_after = Pt(after)
    _set_run_font(p.add_run(text), size=size, bold=bold, color="000000")
    lines = max(1, math.ceil(len(text) / CHARS_PER_LINE)) if text else 1
    b._need(lines * LINE_PT * spacing + before + after)
    return p


